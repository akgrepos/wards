// Turns the AKG Design System's tokens.json into CSS custom properties and text-style classes.
// Run with `npm run tokens` after updating vendor/akg/. Output: src/design/tokens.css (committed).
//
// iOS text styles are written in rem, relative to 17px body text, so they follow the iPhone's
// Text Size setting once `html` uses `font: -apple-system-body` (see src/design/base.css).
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../vendor/akg/tokens.json', import.meta.url), 'utf8'));
const IOS_BODY_PX = 17;

const lines = ['/* Generated by scripts/build-tokens.mjs from vendor/akg/tokens.json. Do not edit by hand. */', ''];

// Theme-independent values: fonts, spacing, radii, shadows, sizes.
lines.push(':root {');
for (const [name, stack] of Object.entries(tokens.type.families)) lines.push(`  --font-${name}: ${stack};`);
for (const group of ['spacing', 'radius', 'shadow', 'size']) {
  for (const t of tokens[group].tokens) lines.push(`  --${t.name}: ${t.value};`);
}
lines.push('}', '');

// A value like "{system-blue}" points at another token.
const resolve = (value) => value.replace(/\{([\w-]+)\}/g, 'var(--$1)');

// Colors, one block per theme. ios-light is also the default when no data-theme is set.
for (const theme of tokens.color.themes) {
  const selector = theme.id === 'ios-light' ? `:root, [data-theme="${theme.id}"]` : `[data-theme="${theme.id}"]`;
  lines.push(`${selector} {`);
  for (const t of tokens.color.tokens) lines.push(`  --${t.name}: ${resolve(t.value[theme.id])};`);
  lines.push('}', '');
}

// Text styles as classes, e.g. .ios-body, .ios-large-title-emphasized.
const rem = (px) => `${+(parseFloat(px) / IOS_BODY_PX).toFixed(4)}rem`;
for (const group of tokens.type.groups) {
  const family = group.family ? `var(--font-${group.family})` : 'var(--font-sans)';
  for (const s of group.styles) {
    const ios = s.name.startsWith('ios-');
    const size = ios ? rem(s.fontSize) : s.fontSize;
    const lineHeight = ios ? rem(s.lineHeight) : s.lineHeight;
    lines.push(`.${s.name} { font-family: ${family}; font-size: ${size}; line-height: ${lineHeight}; font-weight: ${s.fontWeight}; }`);
  }
}
lines.push('');

writeFileSync(new URL('../src/design/tokens.css', import.meta.url), lines.join('\n'));
console.log('Wrote src/design/tokens.css');
